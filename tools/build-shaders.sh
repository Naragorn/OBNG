#!/usr/bin/env bash
# Compiles OBNG's own Direct3D 9 programs (plugin/shaders/*.hlsl) with
# vkd3d-compiler and writes their bytecode as C++ arrays into
# plugin/src/shaders/<Name>Bytecode.h, which the plugin builds in. The header is
# generated but kept in Git, so that the DLL builds without vkd3d; run this
# after changing a .hlsl and commit both.
#
#   tools/build-shaders.sh
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# name, vertex entry, pixel entry
build() {
	local name="$1" vs="$2" ps="$3"
	local src="$root/plugin/shaders/$name.hlsl"
	vkd3d-compiler -x hlsl -b d3dbc -p vs_3_0 -e "$vs" -o "$work/$name.vso" "$src"
	vkd3d-compiler -x hlsl -b d3dbc -p ps_3_0 -e "$ps" -o "$work/$name.pso" "$src"
	python3 -I - "$name" "$work/$name.vso" "$work/$name.pso" "$root/plugin/src/shaders/${name}Bytecode.h" "$(vkd3d-compiler --version 2>&1 | head -1)" <<'PY'
import struct, sys
name, vso, pso, out, version = sys.argv[1:6]
def words(path):
    data = open(path, 'rb').read()
    assert len(data) % 4 == 0, path
    return struct.unpack('<%dI' % (len(data) // 4), data)
def array(ident, values):
    lines = []
    for i in range(0, len(values), 8):
        lines.append('\t' + ', '.join('0x%08Xu' % v for v in values[i:i + 8]) + ',')
    return 'inline constexpr std::uint32_t %s[] = {\n%s\n};\n' % (ident, '\n'.join(lines))
text = ('#pragma once\n'
        '// Generated by tools/build-shaders.sh from plugin/shaders/%s.hlsl - do not edit.\n'
        '// %s\n'
        '#include <cstdint>\n\n'
        'namespace obng::plugin::shaders {\n\n' % (name, version))
text += array('k%sVertex' % name, words(vso)) + '\n'
text += array('k%sPixel' % name, words(pso)) + '\n'
text += '}  // namespace obng::plugin::shaders\n'
open(out, 'w').write(text)
print('wrote', out)
PY
}

build SLS2003Instanced VS PS
